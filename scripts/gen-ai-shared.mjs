#!/usr/bin/env node
// functions は rootDir=src で ../src を読めないため、AI の共有コードを functions/src/ai/shared/ へ写す（実装計画 §4 U3「共有の仕方」）。
//   node scripts/gen-ai-shared.mjs          … 写す
//   node scripts/gen-ai-shared.mjs --check  … 写しが正と違えば exit 1（test:functions の前に走る）
// 正: src/shared/ai/*.ts・src/types/aiDraft.ts・src/types/index.ts（import の相対パスだけ書き換える）
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'functions', 'src', 'ai', 'shared');
const HEADER = '// GENERATED by scripts/gen-ai-shared.mjs — 手で直さない。正は src/ 側（node scripts/gen-ai-shared.mjs で写し直す）\n';

export function plan() {
  const files = [
    { from: 'src/types/index.ts', to: 'types.ts' },
    { from: 'src/types/aiDraft.ts', to: 'aiDraft.ts' },
    ...readdirSync(join(root, 'src', 'shared', 'ai')).filter((f) => f.endsWith('.ts')).sort().map((f) => ({ from: `src/shared/ai/${f}`, to: f })),
  ];
  return files.map(({ from, to }) => {
    // 改行は LF にそろえる（Windows の autocrlf で写しと正の改行が割れても検査が落ちないように）
    const src = readFileSync(join(root, from), 'utf8')
      .replace(/\r\n/g, '\n')
      .replace(/from '\.\.\/\.\.\/types\/index'/g, "from './types'")
      .replace(/from '\.\.\/\.\.\/types\/aiDraft'/g, "from './aiDraft'")
      .replace(/from '\.\/index'/g, "from './types'");
    if (/from '(?:@\/|\.\.\/)/.test(src)) throw new Error(`${from}: 写し先で解決できない import があります（@/ や ../ は使わない）`);
    return { path: join(outDir, to), text: HEADER + src };
  });
}

function main() {
  const check = process.argv.includes('--check');
  const items = plan();
  const stale = items.filter((i) => !existsSync(i.path) || readFileSync(i.path, 'utf8').replace(/\r\n/g, '\n') !== i.text);
  const known = new Set(items.map((i) => i.path));
  const extra = existsSync(outDir) ? readdirSync(outDir).map((f) => join(outDir, f)).filter((p) => !known.has(p)) : [];
  if (check) {
    if (stale.length || extra.length) {
      for (const s of stale) console.error(`[gen-ai-shared] 古い: ${s.path}`);
      for (const e of extra) console.error(`[gen-ai-shared] 正の無いファイル: ${e}`);
      console.error('node scripts/gen-ai-shared.mjs で写し直してください');
      process.exit(1);
    }
    console.log(`[gen-ai-shared] ok (${items.length} files)`);
    return;
  }
  mkdirSync(outDir, { recursive: true });
  for (const i of stale) writeFileSync(i.path, i.text);
  console.log(`[gen-ai-shared] wrote ${stale.length}/${items.length}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
