#!/usr/bin/env node
// AI 下書きの共有コードを functions へ写す（実装計画 §4 U3「共有の仕方」）。functions は rootDir: src で ../src を読めないため。
//   node scripts/gen-ai-shared.mjs          … functions/src/ai/shared/ を書き直す
//   node scripts/gen-ai-shared.mjs --check  … 差分があれば exit 1（test:functions の前に走る。写し忘れ・手で直した写しを止める）
// 正: src/shared/ai/*.ts と src/types/aiDraft.ts。写しは手で直さない（先頭に GENERATED の注記）
// 書き換えるのは import だけ: '@/types/aiDraft' → './aiDraft'、aiDraft.ts の `from './index'` → './typesShim'
import { existsSync, readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'src', 'shared', 'ai');
const OUT = join(root, 'functions', 'src', 'ai', 'shared');
const HEADER = '// GENERATED by scripts/gen-ai-shared.mjs — 手で直さない。正は src/shared/ai/ と src/types/aiDraft.ts\n';

const SHIM = `${HEADER}// src/types/index.ts の型の代わり（functions は v1 の Proposal の中身を使わない）
export type ISODate = string;
export type Proposal = { readonly [key: string]: unknown };
`;

/** 書くべき写し（ファイル名 → 本文） */
export function buildOutputs() {
  const out = new Map();
  const norm = (s) => s.replace(/\r\n/g, '\n');
  for (const f of readdirSync(SRC).filter((x) => x.endsWith('.ts')).sort()) {
    const body = norm(readFileSync(join(SRC, f), 'utf8')).replace(/from '@\/types\/aiDraft'/g, "from './aiDraft'");
    if (/from '@\//.test(body)) throw new Error(`${f}: '@/…' の import は写せません（@/types/aiDraft だけ可）`);
    out.set(f, HEADER + body);
  }
  const ai = norm(readFileSync(join(root, 'src', 'types', 'aiDraft.ts'), 'utf8'));
  const rewritten = ai.replace("from './index';", "from './typesShim';");
  if (rewritten === ai) throw new Error("src/types/aiDraft.ts の `from './index';` が見つかりません");
  out.set('aiDraft.ts', HEADER + rewritten);
  out.set('typesShim.ts', SHIM);
  return out;
}

function main() {
  const check = process.argv.includes('--check');
  const outputs = buildOutputs();
  const existing = existsSync(OUT) ? readdirSync(OUT).filter((x) => x.endsWith('.ts')) : [];
  const stale = existing.filter((f) => !outputs.has(f));
  const diff = [...outputs].filter(([f, body]) => !existsSync(join(OUT, f)) || readFileSync(join(OUT, f), 'utf8').replace(/\r\n/g, '\n') !== body).map(([f]) => f);
  if (check) {
    if (diff.length || stale.length) {
      console.error(`[gen-ai-shared] 写しが古い: ${[...diff, ...stale.map((s) => `${s}（余分）`)].join(', ')}。node scripts/gen-ai-shared.mjs を実行する`);
      process.exit(1);
    }
    console.log(`[gen-ai-shared] ok (${outputs.size} files)`);
    return;
  }
  if (stale.length) throw new Error(`functions/src/ai/shared/ に正の無いファイルがあります: ${stale.join(', ')}（手で消してから再実行）`);
  mkdirSync(OUT, { recursive: true });
  for (const [f, body] of outputs) writeFileSync(join(OUT, f), body);
  console.log(`[gen-ai-shared] wrote ${outputs.size} files (${diff.length} changed)`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
